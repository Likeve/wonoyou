async () => {
  const browser = page.context().browser();
  const a = page;
  const bContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const cContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const b = await bContext.newPage(), c = await cContext.newPage();
  const issues = [];
  for (const p of [a,b,c]) p.on('pageerror', e => issues.push(e.message));
  const create = async (p, name) => {
    await p.goto('http://127.0.0.1:8791');
    await p.getByLabel('你的昵称').fill(name);
    await p.getByRole('button', { name: '创建本地身份' }).click();
    await p.getByText('已连接 · 记录仅存本机', { exact: true }).waitFor();
  };
  const code = async p => {
    await p.getByRole('button', { name: '我', exact: true }).click();
    await p.getByRole('button', { name: '我的身份码', exact: true }).click();
    const id = await p.locator('.id-code').innerText();
    await p.getByRole('button', { name: '关闭', exact: true }).click();
    await p.getByRole('button', { name: '聊天', exact: true }).click();
    return id;
  };
  await create(a, '群主甲'); await create(b, '成员乙'); await create(c, '成员丙');
  const bId = await code(b), cId = await code(c);
  await a.getByRole('button', { name: '创建群聊', exact: true }).click();
  await a.getByLabel('群名称').fill('周末小分队');
  await a.getByLabel('成员身份码').fill('bad');
  await a.getByRole('button', { name: '创建并邀请' }).click();
  await a.getByText('身份码格式不正确', { exact: true }).waitFor();
  await a.getByLabel('成员身份码').fill(bId);
  await a.getByRole('button', { name: '创建并邀请' }).click();
  await a.locator('.chat-header h2').filter({ hasText: '周末小分队' }).waitFor();
  await b.locator('.contact-row').filter({ hasText: '周末小分队' }).waitFor();
  await b.locator('.contact-row').filter({ hasText: '周末小分队' }).click();
  await a.getByLabel('消息', { exact: true }).fill('群聊加密消息测试');
  await a.getByRole('button', { name: '发送', exact: true }).click();
  await b.locator('.bubble').filter({ hasText: '群聊加密消息测试' }).waitFor();
  await b.getByLabel('消息', { exact: true }).fill('乙已收到');
  await b.getByRole('button', { name: '发送', exact: true }).click();
  await a.locator('.bubble').filter({ hasText: '乙已收到' }).waitFor();
  // Existing members can invite; invitees do not become individual contacts.
  await b.getByRole('button', { name: '聊天详情' }).click();
  await b.getByRole('button', { name: '通过身份码邀请' }).click();
  await b.getByLabel('成员身份码').fill(cId);
  await c.goto('about:blank');
  await b.getByRole('button', { name: '确认邀请' }).click();
  await a.getByText('3 位成员 · 群聊').waitFor();
  await a.getByLabel('消息', { exact: true }).fill('丙离线时的群消息');
  await a.getByRole('button', { name: '发送', exact: true }).click();
  await c.goto('http://127.0.0.1:8791');
  await c.locator('.contact-row').filter({ hasText: '周末小分队' }).click();
  await c.locator('.bubble').filter({ hasText: '丙离线时的群消息' }).waitFor();
  if (await c.locator('.bubble').filter({ hasText: '群聊加密消息测试' }).count()) throw Error('New member received pre-invitation history');
  await c.getByLabel('消息', { exact: true }).fill('丙上线了');
  await c.getByRole('button', { name: '发送', exact: true }).click();
  await a.locator('.bubble').filter({ hasText: '丙上线了' }).waitFor();
  await b.locator('.bubble').filter({ hasText: '丙上线了' }).waitFor();
  await a.screenshot({ path: 'output/playwright/group-desktop.png' });
  await c.screenshot({ path: 'output/playwright/group-mobile.png' });
  await a.getByRole('button', { name: '我', exact: true }).click();
  await a.getByRole('button', { name: '检查更新', exact: true }).click();
  await a.getByText('当前已是最新版本', { exact: true }).waitFor();
  await a.screenshot({ path: 'output/playwright/group-update.png' });
  await page.context().setOffline(true);
  await a.getByRole('button', { name: '检查更新', exact: true }).click();
  await a.getByText('当前离线，请联网后检查更新', { exact: true }).waitFor();
  await page.context().setOffline(false);
  if (issues.length) throw Error(issues.join('\n'));
  return { passed: ['invalid code rejection', 'automatic group appearance', 'two-way encrypted chat', 'member invitation', 'offline invite and delivery', 'no old history for new member', 'three-member fanout', 'latest version check', 'offline update message'], pageErrors: issues };
}
